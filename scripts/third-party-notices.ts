const check = process.argv.includes("--check");

const tugdeckManifest = JSON.parse(readFileSync(join(ROOT, "tugdeck/package.json"), "utf8")) as {
  dependencies?: Record<string, string>;
};
const trees: Tree[] = [
  cargoTree("tugrust", MACOS_TARGETS, "Rust crates compiled into tugcast, tugtool, and the other tugrust binaries"),
  cargoTree("tugdeck/crates", WASM_TARGETS, "Rust crates compiled to WebAssembly for tugdeck"),
  bunTree("tugdeck", Object.keys(tugdeckManifest.dependencies ?? {}), "npm packages bundled into tugdeck"),
  bunTree("tugcode", importedPackages("tugcode"), "npm packages compiled into tugcode"),
  swiftTree(),
];
const generated = render(trees);

const current = readFileSync(NOTICES, "utf8");
const at = current.indexOf(MARKER);
const handWritten = at === -1 ? `${current.trimEnd()}\n\n---\n\n` : current.slice(0, at);
const next = handWritten + generated;

if (problems.length > 0) {
  for (const p of problems) console.error(`third-party-notices: ${p}`);
  process.exit(1);
}

if (check) {
  if (at === -1) {
    console.error("third-party-notices: THIRD_PARTY_NOTICES.md has no generated section — run `just notices`");
    process.exit(1);
  }
  if (next !== current) {
    const want = generated.split("\n");
    const have = current.slice(at).split("\n");
    // No differing line within `want` means the committed file runs longer.
    const differs = want.findIndex((l, i) => l !== have[i]);
    const line = differs === -1 ? want.length : differs;
    const lineNo = current.slice(0, at).split("\n").length + line;
    console.error(`third-party-notices: THIRD_PARTY_NOTICES.md:${lineNo} differs from the lockfiles — run \`just notices\``);
    console.error(`  committed: ${have[line] ?? "(end of file)"}`);
    console.error(`  generated: ${want[line] ?? "(end of file)"}`);
    process.exit(1);
  }
  const count = trees.reduce((n, t) => n + t.entries.length, 0);
  console.log(`third-party-notices: ${count} shipped packages, all permissive, notices current`);
} else {
  writeFileSync(NOTICES, next);
  console.log(`third-party-notices: wrote ${relative(ROOT, NOTICES)}`);
}
