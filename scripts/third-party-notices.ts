interface Entry {
  name: string;
  version: string;
  license: string;
  repository: string;
}

interface Tree {
  title: string;
  source: string;
  entries: Entry[];
}

const problems: string[] = [];

function cleanRepo(raw: unknown): string {
  let url = "";
  if (typeof raw === "string") url = raw;
  else if (raw && typeof raw === "object" && typeof (raw as { url?: unknown }).url === "string") {
    url = (raw as { url: string }).url;
  }
  url = url
    .trim()
    .replace(/^git\+/, "")
    .replace(/^git:\/\//, "https://")
    .replace(/^ssh:\/\/git@/, "https://")
    .replace(/^git@github\.com:/, "https://github.com/")
    .replace(/\.git$/, "")
    .replace(/\/$/, "");
  if (/^github:/.test(url)) url = `https://github.com/${url.slice("github:".length)}`;
  else if (/^[\w.-]+\/[\w.-]+$/.test(url)) url = `https://github.com/${url}`;
  return url;
}

function cargoTree(dir: string, targets: string[], title: string): Tree {
  const args = ["metadata", "--format-version", "1", "--locked"];
  for (const t of targets) args.push("--filter-platform", t);
  const proc = Bun.spawnSync(["cargo", ...args], { cwd: join(ROOT, dir), stdout: "pipe", stderr: "pipe" });
  if (proc.exitCode !== 0) {
    throw new Error(`cargo metadata failed in ${dir}:\n${proc.stderr.toString()}`);
  }
  const meta = JSON.parse(proc.stdout.toString()) as {
    packages: { id: string; name: string; version: string; license: string | null; repository: string | null; source: string | null }[];
    workspace_members: string[];
    resolve: { nodes: { id: string; deps: { pkg: string; dep_kinds: { kind: string | null }[] }[] }[] };
  };
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const members = new Set(meta.workspace_members);
  const seen = new Set<string>();
  const stack = [...members];
  while (stack.length > 0) {
    const id = stack.pop()!;
    if (seen.has(id)) continue;
    seen.add(id);
    for (const d of nodes.get(id)?.deps ?? []) {
      if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg);
    }
  }
  const entries: Entry[] = [];
  for (const id of seen) {
    if (members.has(id)) continue;
    const p = byId.get(id)!;
    if (p.source === null) {
      problems.push(`${dir}: ${p.name} is a path dependency outside the workspace; it has no lockfile identity to list`);
      continue;
    }
    entries.push({ name: p.name, version: p.version, license: p.license ?? "", repository: cleanRepo(p.repository) });
  }
  return { title, source: `${dir}/Cargo.lock`, entries };
}

/** bun.lock is JSON with trailing commas. */
function readBunLock(path: string): {
  workspaces: Record<string, { dependencies?: Record<string, string> }>;
  packages: Record<string, [string, string, BunMeta?, string?]>;
} {
  const text = readFileSync(path, "utf8").replace(/,(\s*[}\]])/g, "$1");
  return JSON.parse(text);
}

interface BunMeta {
  dependencies?: Record<string, string>;
  peerDependencies?: Record<string, string>;
  optionalPeers?: string[];
}

function bunTree(dir: string, roots: string[], title: string): Tree {
  const lock = readBunLock(join(ROOT, dir, "bun.lock"));
  const pkgs = lock.packages;
  const nameOf = (key: string) => {
    const spec = pkgs[key][0];
    return spec.slice(0, spec.lastIndexOf("@"));
  };
  const parentOf = (key: string) => {
    const name = nameOf(key);
    return key.length > name.length ? key.slice(0, key.length - name.length - 1) : null;
  };
  /** Node's resolution, expressed over bun.lock's nested keys. */
  const resolve = (from: string | null, dep: string): string | null => {
    for (let k = from; k !== null; k = parentOf(k)) {
      if (pkgs[`${k}/${dep}`]) return `${k}/${dep}`;
    }
    return pkgs[dep] ? dep : null;
  };
  const modulePath = (key: string): string => {
    const parent = parentOf(key);
    const name = nameOf(key);
    return parent === null ? join("node_modules", name) : join(modulePath(parent), "node_modules", name);
  };
  const seen = new Set<string>();
  const stack: string[] = [];
  for (const r of roots) {
    const key = resolve(null, r);
    if (key === null) problems.push(`${dir}: root "${r}" is not in bun.lock`);
    else stack.push(key);
  }
  while (stack.length > 0) {
    const key = stack.pop()!;
    if (seen.has(key)) continue;
    seen.add(key);
    const meta = pkgs[key][2];
    const optionalPeers = new Set(meta?.optionalPeers ?? []);
    // optionalDependencies are left out: in these trees they are per-platform
    // native binaries for Node (pdfjs-dist's canvas) and type packages, and
    // neither reaches a browser bundle or a `bun build --compile` output.
    const deps = [
      ...Object.keys(meta?.dependencies ?? {}),
      ...Object.keys(meta?.peerDependencies ?? {}).filter((d) => !optionalPeers.has(d)),
    ];
    for (const d of deps) {
      const target = resolve(key, d);
      if (target === null) {
        problems.push(`${dir}: ${nameOf(key)} depends on "${d}", which bun.lock does not resolve`);
        continue;
      }
      stack.push(target);
    }
  }

  const entries: Entry[] = [];
  for (const key of seen) {
    const spec = pkgs[key][0];
    const at = spec.lastIndexOf("@");
    const name = spec.slice(0, at);
    const version = spec.slice(at + 1);
    const manifestPath = join(ROOT, dir, modulePath(key), "package.json");
    if (!existsSync(manifestPath)) {
      problems.push(`${dir}: ${relative(ROOT, manifestPath)} is missing — run \`bun install\` in ${dir}`);
      continue;
    }
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as {
      license?: string | { type?: string };
      licenses?: { type?: string }[];
      repository?: unknown;
      version?: string;
    };
    let license = "";
    if (typeof manifest.license === "string") license = manifest.license;
    else if (manifest.license?.type) license = manifest.license.type;
    else if (manifest.licenses?.length) license = manifest.licenses.map((l) => l.type).join(" OR ");
    if (license === "") license = NPM_LICENSE_OVERRIDES[`${name}@${version}`] ?? "";
    // The version is the lockfile's and the license is node_modules'; a stale
    // install would put the old package's license beside the new version.
    if (manifest.version !== version) {
      problems.push(
        `${dir}: ${relative(ROOT, manifestPath)} is ${manifest.version}, bun.lock says ${version} — run \`bun install\` in ${dir}`,
      );
      continue;
    }
    entries.push({ name, version, license, repository: cleanRepo(manifest.repository) });
  }
  return { title, source: `${dir}/bun.lock`, entries };
}

/** The npm packages `dir/src` imports at runtime, outside tests. */
function importedPackages(dir: string): string[] {
  const transpiler = new Bun.Transpiler({ loader: "ts" });
  const found = new Set<string>();
  const walk = (d: string) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) {
        if (name !== "__tests__") walk(p);
      } else if (/\.tsx?$/.test(name) && !/\.test\.tsx?$/.test(name)) {
        const source = readFileSync(p, "utf8").replace(/^#!.*/, "");
        for (const imp of transpiler.scanImports(source)) {
          const spec = imp.path;
          if (spec.startsWith(".") || spec.startsWith("/") || /^(node|bun):/.test(spec) || spec === "bun") continue;
          if (LOCAL_IMPORT_PREFIXES.some((pre) => spec.startsWith(pre))) continue;
          const parts = spec.split("/");
          found.add(spec.startsWith("@") ? `${parts[0]}/${parts[1]}` : parts[0]);
        }
      }
    }
  };
  walk(join(ROOT, dir, "src"));
  return [...found].sort();
}

function swiftTree(): Tree {
  const rel = "tugapp/Tug.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved";
  const resolved = JSON.parse(readFileSync(join(ROOT, rel), "utf8")) as {
    pins: { identity: string; location: string; state: { version?: string; revision: string } }[];
  };
  const entries: Entry[] = [];
  for (const pin of resolved.pins) {
    const known = SWIFT[pin.identity];
    if (!known) {
      problems.push(`${rel}: SwiftPM pin "${pin.identity}" has no entry in the SWIFT table of scripts/third-party-notices.ts`);
      continue;
    }
    entries.push({
      name: known.name,
      version: pin.state.version ?? pin.state.revision.slice(0, 12),
      license: known.license,
      repository: cleanRepo(pin.location),
    });
  }
  return { title: "Swift packages linked into Tug.app", source: rel, entries };
}

