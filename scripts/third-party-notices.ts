function render(trees: Tree[]): string {
  const used = new Set<string>();
  const lines: string[] = [];
  lines.push(MARKER, "");
  lines.push("## Libraries shipped inside Tug.app");
  lines.push("");
  lines.push(
    "Every third-party library the bundle carries, generated from the lockfiles named under each heading. Each row gives the license the package declares; the full text of each license is reproduced once, at the end, rather than once per package. The copyright holders for each package are named in the repository listed beside it.",
  );
  for (const tree of trees) {
    const sorted = [...tree.entries].sort((a, b) =>
      a.name === b.name ? Bun.semver.order(a.version, b.version) : a.name < b.name ? -1 : 1,
    );
    lines.push("", "---", "", `### ${tree.title}`, "", `From \`${tree.source}\` — ${sorted.length} ${sorted.length === 1 ? "package" : "packages"}.`, "");
    lines.push("| Package | Version | License | Repository |", "|---|---|---|---|");
    for (const e of sorted) {
      let elected: string[] | null = null;
      if (e.license === "") {
        problems.push(`${tree.source}: ${e.name} ${e.version} declares no license`);
      } else {
        try {
          elected = elect(parseSpdx(e.license));
        } catch (err) {
          problems.push(`${tree.source}: ${e.name} ${e.version}: ${(err as Error).message}`);
        }
        if (elected === null) {
          problems.push(
            `${tree.source}: ${e.name} ${e.version} is licensed "${e.license}", outside the allow-list (${ALLOWED.join(", ")})`,
          );
        }
      }
      for (const id of elected ?? []) used.add(id);
      const repo = e.repository === "" ? "—" : e.repository;
      lines.push(`| ${e.name} | ${e.version} | ${e.license.replace(/\|/g, "\\|") || "—"} | ${repo} |`);
    }
  }
  lines.push("", "---", "", "### License texts", "");
  lines.push(
    "One copy of each license the packages above are used under. Where a package offers a choice, it is used under the first of these that it offers.",
  );
  const seenText = new Set<string>();
  for (const id of ALLOWED) {
    if (!used.has(id) || seenText.has(LICENSE_TEXTS[id])) continue;
    seenText.add(LICENSE_TEXTS[id]);
    const aliases = ALLOWED.filter((a) => used.has(a) && LICENSE_TEXTS[a] === LICENSE_TEXTS[id]);
    lines.push("", `#### ${aliases.join(", ")}`, "", "```", LICENSE_TEXTS[id], "```");
  }
  return `${lines.join("\n")}\n`;
}

