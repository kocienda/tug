// ---------------------------------------------------------------------------
// SPDX expressions
// ---------------------------------------------------------------------------

type Expr =
  | { op: "id"; id: string }
  | { op: "and" | "or"; args: Expr[] };

function parseSpdx(raw: string): Expr {
  // Old crates write `MIT/Apache-2.0` for an OR; normalise before tokenising.
  const tokens = raw.replace(/\//g, " OR ").match(/\(|\)|[^\s()]+/g) ?? [];
  let i = 0;
  const peek = () => tokens[i];
  function primary(): Expr {
    const t = tokens[i++];
    if (t === undefined) throw new Error(`unexpected end of license expression "${raw}"`);
    if (t === "(") {
      const e = or();
      if (tokens[i++] !== ")") throw new Error(`unbalanced parentheses in "${raw}"`);
      return e;
    }
    if (peek() === "WITH") {
      i++;
      const exception = tokens[i++];
      if (!ALLOWED_EXCEPTIONS.has(exception ?? "")) {
        throw new Error(`license exception "${exception}" in "${raw}" is not admitted`);
      }
    }
    return { op: "id", id: t };
  }
  function and(): Expr {
    const args = [primary()];
    while (peek() === "AND") {
      i++;
      args.push(primary());
    }
    return args.length === 1 ? args[0] : { op: "and", args };
  }
  function or(): Expr {
    const args = [and()];
    while (peek() === "OR") {
      i++;
      args.push(and());
    }
    return args.length === 1 ? args[0] : { op: "or", args };
  }
  const e = or();
  if (i !== tokens.length) throw new Error(`trailing tokens in license expression "${raw}"`);
  return e;
}

/** The license ids an expression is used under, or null when nothing allowed satisfies it. */
function elect(e: Expr): string[] | null {
  if (e.op === "id") return ALLOWED.includes(e.id) ? [e.id] : null;
  if (e.op === "and") {
    const all: string[] = [];
    for (const a of e.args) {
      const got = elect(a);
      if (got === null) return null;
      all.push(...got);
    }
    return all;
  }
  const options = e.args.map(elect).filter((x): x is string[] => x !== null);
  if (options.length === 0) return null;
  const rank = (ids: string[]) => Math.max(...ids.map((id) => ALLOWED.indexOf(id)));
  options.sort((a, b) => rank(a) - rank(b));
  return options[0];
}

