#!/usr/bin/env bun
/**
 * third-party-notices — generate the "libraries shipped inside Tug.app" half
 * of `THIRD_PARTY_NOTICES.md` from the lockfiles, and check it.
 *
 *   bun scripts/third-party-notices.ts           # rewrite the generated half
 *   bun scripts/third-party-notices.ts --check   # fail on drift or a license outside the allow-list
 *
 * The file has two halves. Everything above MARKER is hand-written: the L21
 * entries for code and patterns adopted into this checkout, and the binaries
 * the bundle carries that no lockfile names (tmux and its libraries, fonts).
 * Everything below it is this script's output, and nothing else writes there.
 *
 * What ships, per tree:
 *   - `tugrust/Cargo.lock` — every crate a workspace member reaches through
 *     normal (not dev, not build) dependency edges on the macOS targets, read
 *     through `cargo metadata`.
 *   - `tugdeck/crates/Cargo.lock` — the same for the wasm crates, on
 *     `wasm32-unknown-unknown`; their output ships in the deck bundle.
 *   - `tugdeck/bun.lock` — the closure of `tugdeck/package.json`'s
 *     `dependencies`; its `devDependencies` are build tools and never ship.
 *   - `tugcode/bun.lock` — tugcode declares every package as a dev
 *     dependency, so its roots are the packages `tugcode/src` actually
 *     imports at runtime (type-only imports excluded); `bun build --compile`
 *     bundles exactly those.
 *   - `Package.resolved` — the SwiftPM pins, through the SWIFT table below.
 *
 * A license is read from each package's own manifest (`Cargo.toml` via cargo
 * metadata, `package.json` from node_modules), parsed as an SPDX expression,
 * and elected: an OR takes its first allowed alternative, an AND needs every
 * operand allowed. The allow-list is the keys of LICENSE_TEXTS — so admitting
 * a new license means writing its text here, which is the review L21 asks for.
 * Contract: [L21] in tuglaws/tuglaws.md, and the no-GPL rule [D171] rides.
 */
