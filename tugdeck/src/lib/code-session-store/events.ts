/** Internal `send` action injected by `CodeSessionStore.send`. */
/**
 * A `$`-route shell exchange entered the transcript ([P06]/[P12]). NOT a wire
 * event — `ShellSessionStore` folds `SHELL_OUTPUT` and calls
 * `codeSessionStore.ingestShellExchange`, which dispatches these. The exchange
 * becomes a committed `shell`-origin `TurnEntry` in `transcript` (never the
 * Claude `activeTurn` slot), correlated by `exchangeId`.
 */
export interface ShellExchangeStartedActionEvent {
  type: "shell_exchange_started";
  exchangeId: string;
  command: string;
  cwd: string;
  startedAtMs: number;
  /** True when the PATH classifier auto-routed this line to the shell ([P09]). */
  autoRouted?: boolean;
}

export interface ShellExchangeCompleteActionEvent {
  type: "shell_exchange_complete";
  exchangeId: string;
  /** Present when a matching `started` exists; carried for a bare complete
   *  (restore / no prior started) so the turn can be minted whole. */
  command: string;
  output: string;
  /** `null` = killed / timed-out / in-flight. */
  exitCode: number | null;
  cwd: string;
  cwdAfter: string | null;
  startedAtMs: number;
  settledAtMs: number;
  /** True when the PATH classifier auto-routed this line to the shell ([P09]). */
  autoRouted?: boolean;
  /**
   * Restore only: the ledger row's `anchor_msg_id` — the transcript turn this
   * exchange was written after. Absent on a live exchange, whose correct
   * position is the transcript's end at the moment it happens.
   * @see TurnEntry.anchorMsgId
   */
  anchorMsgId?: string;
}

/**
 * A `/match` or `/search` run's current state entered the transcript. NOT a
 * wire event — `RefsSessionStore` folds `REFS_OUTPUT` and calls
 * `codeSessionStore.ingestRefs`, which dispatches this.
 *
 * The event carries the run's WHOLE state, not a delta: the refs store owns
 * the accumulating row list (it answers `/ref N` from the same list), so the
 * transcript replaces its message rather than appending to it. One event
 * shape covers mint, every streaming update, and settle.
 */
export interface RefsResultActionEvent {
  type: "refs_result";
  runId: string;
  opKind: "match" | "search";
  command: string;
  root: string;
  refs: ReadonlyArray<TextRef>;
  inFlight: boolean;
  cancelled: boolean;
  notice: string | null;
  startedAtMs: number;
  settledAtMs: number | null;
  /**
   * Restore only: the ledger row's `anchor_msg_id` — the transcript turn this
   * run was written after. Absent on a live run.
   * @see TurnEntry.anchorMsgId
   */
  anchorMsgId?: string;
}

export interface SendActionEvent {
  type: "send";
  /**
   * Synthesized substrate text — contains `U+FFFC` (object
   * replacement) at every position where the wire's content blocks
   * carry an image. File-path atoms have already been substituted
   * into surrounding text by the synthesizer.
   *
   * Built by `synthesizeUserMessageFromBlocks` in the impure store
   * wrapper before dispatch (the reducer is pure and must not call
   * the synthesizer, which both reads and writes the per-card
   * bytes-store). Goes onto the `UserMessage` Message in the scratch
   * entry so the transcript chip renderer can walk `text` looking
   * for `U+FFFC` and read the corresponding atom for chip placement.
   *
   * Per [Step 5c](../../../dash/dev-atoms.md#step-5c).
   */
  text: string;
  /**
   * Parallel synthesized atom array — one entry per `U+FFFC` in
   * `text`. Image atoms carry `label: "image-N"` (1-based per message) —
   * the same unified name minted at attach time in the editor, rendered
   * verbatim on every surface. Goes onto `UserMessage.attachments` for
   * the substrate's atom lookup at render / replay time.
   */
  atoms: AtomSegment[];
  /**
   * Anthropic-API-shaped content blocks for the wire. Built by
   * `buildWirePayload` from the editor's `(text, atoms)` pair and
   * forwarded verbatim on the `user_message` IPC frame; the reducer
   * just hands it to the `send-frame` effect.
   *
   * Per [Step 5c](../../../dash/dev-atoms.md#step-5c) and
   * [Spec S03](../../../dash/dev-atoms.md#s03-build-wire-payload).
   */
  content: ContentBlock[];
  /**
   * Stable per-turn React-key seed, generated by the store wrapper
   * before dispatch (the reducer is pure and must not call
   * `crypto.randomUUID()` itself). Threaded onto `pendingUserMessage`
   * by `handleSend` and preserved through `handleTurnComplete` onto
   * the committed `TurnEntry`. See `TurnEntry.turnKey` for the
   * cell-stability invariant this drives.
   */
  turnKey: string;
  /**
   * When true, the turn is sent to claude (it runs a real turn and
   * answers in context) but is **never committed to the transcript** —
   * the in-flight rows are skipped and `turn_complete` drops the append.
   * Used for the `/compact` seed: the summary must enter claude's context
   * without showing as a turn (the compaction divider stands in its
   * place). A single-use, single-turn suppression.
   */
  suppress?: boolean;
}

