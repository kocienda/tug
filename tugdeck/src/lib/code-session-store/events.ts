/**
 * `turn_complete` — closes the active turn.
 *
 * `result`:
 *  - `"success"` — the turn finished cleanly (`stop_reason: end_turn`).
 *  - `"error"` — the turn ended on a protocol error.
 *  - `"interrupted"` — an explicit cut-off terminal. tugcode's replay
 *    translator emits this for orphan-interrupted submissions and for
 *    a dangling cold-resume turn (a JSONL cycle with no `end_turn`);
 *    the reducer commits it with `turnEndReason: "interrupted"`.
 *
 * `telemetry` is populated on the replay path only: when the
 * supervisor reads a per-turn telemetry row from the SessionLedger
 * for the matching `msg_id`, it inlines that block onto the replayed
 * `turn_complete` event. Live `turn_complete` events from the wire
 * never carry telemetry — the reducer derives it from in-memory
 * clock anchors + cost snapshots. See `mergeTurnTelemetry` in
 * `telemetry.ts` and the design in plan `#step-20-3-3`.
 */
export interface TurnCompleteEvent {
  type: "turn_complete";
  msg_id: string;
  result: "success" | "error" | "interrupted";
  tug_session_id?: string;
  telemetry?: import("./telemetry").TurnTelemetry;
  /**
   * Optional original wall-clock timestamp (epoch ms) of the terminal
   * assistant JSONL entry that closes this turn. Set only on the replay
   * path so the reducer stamps the committed `TurnEntry.endedAt` with
   * the original completion time. Live `turn_complete` frames omit it
   * and the reducer falls back to `Date.now()`.
   */
  timestamp?: number;
  [key: string]: unknown;
}

